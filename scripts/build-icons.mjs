// Writes public/icons.js from a lucide-react install (ISC), the icon set Sippar's connector page uses (adopted from
// Nuru-AI/sippar demos/connector/build-icons.mjs).
// Usage: node scripts/build-icons.mjs <path to lucide-react> public/icons.js <icon-name> <icon-name> ...
// Pass every icon the page uses, not only the new one: the file is rewritten whole.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
const dir = process.argv[2] + '/dist/esm/icons/';
const outFile = process.argv[3];
const names = process.argv.slice(4);
const out = {}; const missing = [];
for (const n of names) {
  const f = dir + n + '.js';
  if (!existsSync(f)) { missing.push(n); continue; }
  const src = readFileSync(f, 'utf8');
  const m = src.match(/const __iconNode = (\[[\s\S]*?\]);\nconst/);
  const node = new Function('return ' + m[1])();
  out[n] = node.map(([tag, attrs]) => '<' + tag + ' ' + Object.entries(attrs).filter(([k]) => k !== 'key').map(([k, v]) => `${k}="${v}"`).join(' ') + '/>').join('');
}
writeFileSync(outFile, "/* Icons from lucide-react (ISC License, lucide.dev), the set Sippar's connector page uses.\n   Generated by scripts/build-icons.mjs; do not edit by hand. */\nglobalThis.NURU_ICONS=" + JSON.stringify(out) + ';\n');
console.log('wrote', Object.keys(out).length, 'missing:', missing.join(',') || 'none');
